"""Bakes the three click sounds into engine/src/main/cpp/render/ClickData.cpp.

The engine has no asset load: each click is a float array compiled into the
library (about 30 ms at 48 kHz). This script is the one source of those arrays;
run it from the repository root after changing a sound and commit the output.
Standard library only, deterministic (fixed noise seed), so the output is
byte-for-byte reproducible.

    python3 engine/tools/gen_clicks.py
"""
import math
import os
import sys

RATE = 48000
FRAMES = 1440  # 30 ms
PEAK = 0.9
FADE_FRAMES = 96  # 2 ms fade-out so every click ends in silence


def envelope(t, tau):
    return math.exp(-t / tau)


def wood(n):
    # Two damped partials in a wood-block register, cosine phase so the first
    # sample already carries the attack (MET-03 lands on the onset frame).
    t = n / RATE
    return (0.8 * math.cos(2 * math.pi * 1900 * t) * envelope(t, 0.004)
            + 0.4 * math.cos(2 * math.pi * 3100 * t) * envelope(t, 0.0025))


class Lcg:
    """A tiny deterministic generator; random.Random could change across versions."""

    def __init__(self, seed):
        self.state = seed & 0xFFFFFFFF

    def next_unit(self):
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return self.state / 0x100000000 * 2.0 - 1.0


def click(n, rng):
    t = n / RATE
    sample = rng.next_unit() * envelope(t, 0.0015)
    if n == 0:
        sample = 1.0  # a definite first sample: the onset is the attack
    return sample


def beep(n):
    t = n / RATE
    return math.cos(2 * math.pi * 1000 * t) * envelope(t, 0.012)


def bake(fn):
    data = [fn(n) for n in range(FRAMES)]
    peak = max(abs(x) for x in data)
    data = [x / peak * PEAK for x in data]
    for i in range(FADE_FRAMES):
        n = FRAMES - FADE_FRAMES + i
        data[n] *= 1.0 - (i + 1) / FADE_FRAMES
    return data


def emit(name, data, out):
    out.write(f"const float {name}[kClickFrames] = {{\n")
    for i in range(0, FRAMES, 8):
        row = ", ".join(f"{x:.7e}f" for x in data[i:i + 8])
        out.write(f"    {row},\n")
    out.write("};\n\n")


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    target = os.path.join(root, "engine", "src", "main", "cpp", "render", "ClickData.cpp")
    rng = Lcg(0x5EED)
    sounds = [
        ("kWoodData", bake(wood)),
        ("kClickData", bake(lambda n: click(n, rng))),
        ("kBeepData", bake(beep)),
    ]
    with open(target, "w", encoding="utf-8") as out:
        out.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
        out.write("//\n// Generated by engine/tools/gen_clicks.py; edit the script, never this file.\n")
        out.write(f"// Three clicks of {FRAMES} frames at {RATE} Hz, peak {PEAK}, baked so the\n")
        out.write("// engine loads no asset and the first sample of each is the attack.\n")
        out.write('#include "Clicks.h"\n\nnamespace ticktock::render {\n\n')
        for name, data in sounds:
            emit(name, data, out)
        out.write("}  // namespace ticktock::render\n")
    print(f"wrote {os.path.relpath(target, root)}", file=sys.stderr)


if __name__ == "__main__":
    main()
